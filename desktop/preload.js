const {
contextBridge,
ipcRenderer
} =
require(
"electron"
);

const listeners =
new Set();

ipcRenderer.on(
"desktop:update-status",
(
_event,
payload
)=>{
for(
const fn of
listeners
){
try{
fn(
payload
);
}catch(
err
){
console.warn(
"desktop update listener:",
err
);
}
}
}
);

contextBridge.exposeInMainWorld(
"cryptoTerminalDesktop",
{
isDesktop:
true,
platform:
process.platform,
getVersion:()=>
ipcRenderer.invoke(
"app:getVersion"
),
checkForUpdates:()=>
ipcRenderer.invoke(
"app:checkForUpdates"
),
performUpdate:()=>
ipcRenderer.invoke(
"app:performUpdate"
),
downloadUpdate:()=>
ipcRenderer.invoke(
"app:downloadUpdate"
),
installUpdate:()=>
ipcRenderer.invoke(
"app:installUpdate"
),
onAuthCallback:(
callback
)=>{
if(
typeof callback !==
"function"
){
return ()=>{};
}
const fn =
(
_event,
url
)=>{
try{
callback(
url
);
}catch(
err
){
console.warn(
"desktop auth listener:",
err
);
}
};
ipcRenderer.on(
"desktop:auth-callback",
fn
);
return ()=>{
ipcRenderer.removeListener(
"desktop:auth-callback",
fn
);
};
},
onUpdateStatus:(
callback
)=>{
if(
typeof callback !==
"function"
){
return ()=>{};
}
listeners.add(
callback
);
return ()=>{
listeners.delete(
callback
);
};
},
loadAuthSession:()=>
ipcRenderer.invoke(
"desktop:loadAuthSession"
),
saveAuthSession:(
raw
)=>
ipcRenderer.invoke(
"desktop:saveAuthSession",
raw
),
clearAuthSession:()=>
ipcRenderer.invoke(
"desktop:clearAuthSession"
),
trading:{
getStatus:()=>
ipcRenderer.invoke(
"trading:getStatus"
),
saveKeys:(
payload
)=>
ipcRenderer.invoke(
"trading:saveKeys",
payload
),
clearKeys:()=>
ipcRenderer.invoke(
"trading:clearKeys"
),
getWalletBalance:()=>
ipcRenderer.invoke(
"trading:getWalletBalance"
),
getPositions:()=>
ipcRenderer.invoke(
"trading:getPositions"
),
getOpenOrders:()=>
ipcRenderer.invoke(
"trading:getOpenOrders"
),
getPosition:(
symbol
)=>
ipcRenderer.invoke(
"trading:getPosition",
{
symbol
}
),
closePosition:(
symbol
)=>
ipcRenderer.invoke(
"trading:closePosition",
{
symbol
}
),
cancelPositionStop:(
symbol,
target
)=>
ipcRenderer.invoke(
"trading:cancelPositionStop",
{
symbol,
target
}
),
setPositionStop:(
symbol,
target,
price
)=>
ipcRenderer.invoke(
"trading:setPositionStop",
{
symbol,
target,
price
}
),
placeOrder:(
payload
)=>
ipcRenderer.invoke(
"trading:placeOrder",
payload
),
cancelOrder:(
symbol,
orderId
)=>
ipcRenderer.invoke(
"trading:cancelOrder",
{
symbol,
orderId
}
),
amendOrder:(
payload
)=>
ipcRenderer.invoke(
"trading:amendOrder",
payload
),
openPosition:(
symbol,
side,
volumeUsdt
)=>
ipcRenderer.invoke(
"trading:openPosition",
{
symbol,
side,
volumeUsdt
}
),
pingBybit:(
payload
)=>
ipcRenderer.invoke(
"trading:pingBybit",
payload ||
{}
)
}
}
);
